var SAPISID = row(".youtube.com", "SAPISID", "invented-sapisid", false)
var THIRD_PARTY = row(".youtube.com", "__Secure-3PAPISID", "invented-3papisid", false)
var PREF = row("www.youtube.com", "PREF", "invented-pref", false)
var BARE = row("youtube.com", "SOCS", "invented-socs", false)
var EMPTY_VALUE = row(".youtube.com", "EMPTY", "", false)

