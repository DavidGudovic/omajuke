test("the export keeps YouTube's rows and nothing else, in a private file", function() {
  var mine = [SAPISID, LOGIN, PREF, BARE, THIRD_PARTY, EMPTY_VALUE]
  var mixed = [FOREIGN[0], SAPISID, FOREIGN[1], LOGIN, FOREIGN[2], MALFORMED[0], PREF, FOREIGN[3], BARE]
    .concat(FOREIGN.slice(4), [THIRD_PARTY], MALFORMED.slice(1), [EMPTY_VALUE])
  var b = ready(mixed)
  var result = cookieExport(b)
  assert.strictEqual(result.stdout, "ok\n")
  assert.strictEqual(result.stderr, "")
  assert.strictEqual(result.status, 0)
  assert.strictEqual(fs.readFileSync(b.paths.jarFile, "utf8"), HEADER + mine.join("\n") + "\n")
  assert.strictEqual(mode(b.paths.jarFile), "600")
  assert.strictEqual(mode(b.paths.dataDir), "700")
  assert.deepStrictEqual(names(b.paths.dataDir), ["cookies.txt"], "no temporary file is left")
  assert.strictEqual(exists(b.attempt), false, "the profile and the unfiltered export are gone")
  assert.deepStrictEqual(names(b.paths.signinDir), [])
})

test("every row that is kept names youtube.com or a subdomain of it", function() {
  var b = ready(FOREIGN.concat(MALFORMED, [LOGIN, SAPISID]))
  assert.strictEqual(cookieExport(b).stdout, "ok\n")
  var rows = fs.readFileSync(b.paths.jarFile, "utf8").slice(HEADER.length).split("\n").filter(Boolean)
  assert.deepStrictEqual(rows, [LOGIN, SAPISID])
  var text = fs.readFileSync(b.paths.jarFile, "utf8")
  assert.ok(text.indexOf("google") === -1 && text.indexOf("example") === -1)
  assert.ok(text.indexOf("generated by a test") === -1, "the header is our own, not copied")
})

