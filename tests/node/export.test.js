test("prepare-data tightens a data directory that exists with a wider mode", function() {
  var b = box()
  fs.mkdirSync(b.paths.dataDir, { recursive: true })
  fs.chmodSync(b.paths.dataDir, 0o755)
  assert.deepStrictEqual(prepareData(b).tokens, ["ok"])
  assert.strictEqual(mode(b.paths.dataDir), "700")
})

test("prepare-data refuses a data directory that is a link or not a directory", function() {
  var linked = box()
  var elsewhere = path.join(linked.root, "elsewhere")
  fs.mkdirSync(elsewhere)
  fs.chmodSync(elsewhere, 0o755)
  fs.writeFileSync(path.join(elsewhere, "cookies.txt"), "kept\n")
  fs.writeFileSync(path.join(elsewhere, ".cookies.txt.AbC123"), "kept\n")
  fs.mkdirSync(path.dirname(linked.paths.dataDir), { recursive: true })
  fs.symlinkSync(elsewhere, linked.paths.dataDir)
  var refused = prepareData(linked)
  assert.strictEqual(refused.status, 3)
  assert.deepStrictEqual(refused.tokens, ["bad-dir"])
  assert.strictEqual(mode(elsewhere), "755", "the link's target keeps its mode")
  assert.deepStrictEqual(names(elsewhere), [".cookies.txt.AbC123", "cookies.txt"], "and its files")
  assert.strictEqual(mode(path.join(elsewhere, "cookies.txt")), "644")

  var dangling = box()
  fs.mkdirSync(path.dirname(dangling.paths.dataDir), { recursive: true })
  fs.symlinkSync(path.join(dangling.root, "not-there"), dangling.paths.dataDir)
  assert.deepStrictEqual(prepareData(dangling).tokens, ["bad-dir"])
  assert.strictEqual(exists(path.join(dangling.root, "not-there")), false, "nothing is made through a link")

  var file = box()
  fs.mkdirSync(path.dirname(file.paths.dataDir), { recursive: true })
  fs.writeFileSync(file.paths.dataDir, "a file\n")
  var blocked = prepareData(file)
  assert.strictEqual(blocked.status, 3)
  assert.deepStrictEqual(blocked.tokens, ["bad-dir"])
  assert.strictEqual(fs.readFileSync(file.paths.dataDir, "utf8"), "a file\n")
})

test("prepare-data reports a login only if it is a regular file of ours, and makes it private", function() {
  var b = box()
  fs.mkdirSync(b.paths.dataDir, { recursive: true })
  fs.writeFileSync(b.paths.jarFile, HEADER)
  fs.chmodSync(b.paths.jarFile, 0o644)
  assert.deepStrictEqual(prepareData(b).tokens, ["jar", "ok"])
  assert.strictEqual(mode(b.paths.jarFile), "600")
  assert.strictEqual(fs.readFileSync(b.paths.jarFile, "utf8"), HEADER, "it is not read or rewritten")

  var linked = box()
  var target = path.join(linked.root, "someone-elses.txt")
  fs.writeFileSync(target, HEADER)
  fs.chmodSync(target, 0o644)
  fs.mkdirSync(linked.paths.dataDir, { recursive: true })
  fs.symlinkSync(target, linked.paths.jarFile)
  assert.deepStrictEqual(prepareData(linked).tokens, ["ok"], "a link is no login")
  assert.strictEqual(mode(target), "644", "and what it points to is left alone")

  var dir = box()
  fs.mkdirSync(dir.paths.jarFile, { recursive: true })
  assert.deepStrictEqual(prepareData(dir).tokens, ["ok"], "a directory is no login")
})

test("prepare-data deletes only the export's own unfinished files", function() {
  var b = box()
  fs.mkdirSync(b.paths.dataDir, { recursive: true })
  var kept = ["cookies.txt", "cookies.txt.bak", ".cookies.txt.toolong", ".cookies.txt.short", "notes.txt",
    ".cookies.txt", "cookies.txt.AbC123"]
  var deleted = [".cookies.txt.AbC123", ".cookies.txt.000000"]
  kept.concat(deleted).forEach(function(name) { fs.writeFileSync(path.join(b.paths.dataDir, name), "x\n") })
  // A directory with a matching name is not a file of ours, and what is
  // below a subdirectory is not looked at.
  fs.mkdirSync(path.join(b.paths.dataDir, ".cookies.txt.dir123"))
  fs.mkdirSync(path.join(b.paths.dataDir, "sub"))
  fs.writeFileSync(path.join(b.paths.dataDir, "sub", ".cookies.txt.AbC123"), "x\n")
  assert.deepStrictEqual(prepareData(b).tokens, ["jar", "ok"])
  assert.deepStrictEqual(names(b.paths.dataDir), kept.concat([".cookies.txt.dir123", "sub"]).sort())
  assert.deepStrictEqual(names(path.join(b.paths.dataDir, "sub")), [".cookies.txt.AbC123"])
})

test("prepare-data treats hostile directory names as names", function() {
  var homes = ["first last", "o'brien", "a\"b", "$(touch pwned)", "`touch pwned`", "semi;touch pwned", "-rf",
    "star*"]
  homes.forEach(function(home) {
    var b = box(home)
    var result = prepareData(b)
    assert.deepStrictEqual(result.tokens, ["ok"], home)
    assert.strictEqual(result.stderr, "", home)
    assert.strictEqual(mode(b.paths.dataDir), "700", home)
    fs.writeFileSync(b.paths.jarFile, HEADER)
    assert.deepStrictEqual(prepareData(b).tokens, ["jar", "ok"], home)
    assert.strictEqual(exists(path.join(top, "pwned")), false, home)
    assert.strictEqual(exists(path.join(b.root, "pwned")), false, home)
  })
})

