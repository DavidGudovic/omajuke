// Tests for the shell constants of signing in (lib/Sh.js): PREPARE_DATA,
// SIGNIN_DIRS and COOKIE_EXPORT. They are run for real with /usr/bin/sh,
// under umask 022, inside a directory this file creates below the system's
// temporary directory and removes again. Nothing outside it is written.
//
// No browser and no real yt-dlp is involved, and no real profile is read:
// the export is given a stand-in for yt-dlp that this file writes, which
// records how it was started and writes a cookie file made of the invented
// rows below. One test ends a child, through the handle it spawned it with.
var test = require("node:test")
var assert = require("node:assert")
var childProcess = require("node:child_process")
var fs = require("node:fs")
var os = require("node:os")
var path = require("node:path")
var load = require("./load.js")

var Sh = load.lib("Sh")
var Paths = load.lib("Paths")

var SH = "/usr/bin/sh"
var TAB = "\t"
var HEADER = "# Netscape HTTP Cookie File\n\n"

// The modes below are only meaningful under the umask the shell runs with.
process.umask(0o022)

var top = fs.mkdtempSync(path.join(os.tmpdir(), "oj-export-"))
var boxes = 0

test.after(function() {
  fs.rmSync(top, { recursive: true, force: true })
})

// ---- The stand-in for yt-dlp ----

// What it does is chosen by the file "mode" next to it: "write" puts the
// file "rows" where --cookies points, "nothing" writes no file, "link"
// plants a link there, "slow" writes and then stays for a moment. Like the
// real tool run without a URL, it ends with status 2.
var FAKE = [
  "#!/usr/bin/node",
  "\"use strict\"",
  "var fs = require(\"fs\")",
  "var path = require(\"path\")",
  "var here = __dirname",
  "var args = process.argv.slice(2)",
  "fs.appendFileSync(path.join(here, \"log\"), JSON.stringify({",
  "  argv: args, env: Object.keys(process.env).sort(), tmpdir: process.env.TMPDIR || null",
  "}) + \"\\n\")",
  "var mode = fs.readFileSync(path.join(here, \"mode\"), \"utf8\").trim()",
  "var target = args[args.indexOf(\"--cookies\") + 1]",
  "var rows = path.join(here, \"rows\")",
  "if (mode === \"link\") fs.symlinkSync(rows, target)",
  "if (mode === \"write\" || mode === \"slow\") fs.writeFileSync(target, fs.readFileSync(rows))",
  "if (mode === \"slow\") {",
  "  fs.writeFileSync(path.join(here, \"started\"), \"\")",
  "  setTimeout(function() { process.exit(2) }, 700)",
  "} else {",
  "  process.exit(2)",
  "}"
].join("\n") + "\n"

// ---- Invented cookies ----

function row(domain, name, value, httpOnly) {
  var fields = [domain, domain.charAt(0) === "." ? "TRUE" : "FALSE", "/", "TRUE", "1893456000", name, value]
  return (httpOnly ? "#HttpOnly_" : "") + fields.join(TAB)
}

