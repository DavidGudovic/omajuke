test("ended with SIGTERM, the export removes the attempt directory and saves nothing", async function() {
  var b = ready([LOGIN, SAPISID])
  fs.writeFileSync(path.join(b.tool, "mode"), "slow")
  var argv = ["-c", Sh.COOKIE_EXPORT, "omajuke-export"].concat(exportArgs(b))
  var child = childProcess.spawn(SH, argv, { cwd: top, env: { PATH: "/usr/bin", LANG: "C.UTF-8" } })
  var out = ""
  child.stdout.on("data", function(chunk) { out += chunk })
  var ended = new Promise(function(resolve) {
    child.on("close", function(code, signal) { resolve({ code: code, signal: signal }) })
  })
  // The stand-in has written the unfiltered export and is still running.
  var started = path.join(b.tool, "started")
  for (var i = 0; i < 200 && !exists(started); i++) {
    await new Promise(function(resolve) { setTimeout(resolve, 25) })
  }
  assert.strictEqual(exists(started), true)
  assert.strictEqual(exists(b.attempt + "/export.txt"), true)
  child.kill("SIGTERM")
  var result = await ended
  assert.strictEqual(result.code, 1)
  assert.strictEqual(out, "", "nothing is reported for an export that was ended")
  assert.strictEqual(exists(b.attempt), false, "the profile and the unfiltered export are gone")
  assert.deepStrictEqual(names(b.paths.dataDir), [], "and no login was saved, finished or not")
})

test("the attempt directory goes on every exit the export makes itself", function() {
  var text = Sh.COOKIE_EXPORT
  var lines = text.split("\n")
  assert.strictEqual(lines[0], "umask 077")
  // The traps are set before anything can fail or be read.
  assert.match(lines[2], /^trap '\/usr\/bin\/rm -rf -- "\$3"; .*' EXIT$/)
  assert.strictEqual(lines[3], "trap 'exit 1' HUP INT TERM")
  assert.ok(text.indexOf("\"$5\"") > text.indexOf("trap 'exit 1' HUP INT TERM"))
  // Nothing replaces or clears them later.
  assert.strictEqual(text.split("trap ").length - 1, 2)
})
