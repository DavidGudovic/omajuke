function exported(lines) {
  return "# Netscape HTTP Cookie File\n# This file is generated by a test.  Do not edit.\n\n"
    + lines.join("\n") + "\n"
}

// ---- Test directories ----

// A fresh test directory laid out the way the plugin's paths are: a private
// runtime directory with the directory of sign-in attempts, a home, and
// the stand-in tool with its files.
function box(homeName) {
  var root = path.join(top, String(++boxes))
  var runtimeBase = path.join(root, "run")
  var paths = Paths.resolve({
    XDG_RUNTIME_DIR: runtimeBase, XDG_STATE_HOME: null, XDG_DATA_HOME: null,
    HOME: path.join(root, homeName || "home")
  })
  assert.strictEqual(paths.ok, true)
  fs.mkdirSync(paths.signinDir, { recursive: true, mode: 0o700 })
  var tool = path.join(root, "tool")
  fs.mkdirSync(tool)
  fs.writeFileSync(path.join(tool, "yt-dlp"), FAKE, { mode: 0o755 })
  fs.chmodSync(path.join(tool, "yt-dlp"), 0o755)
  var b = {
    root: root, paths: paths, tool: tool, ytdlp: path.join(tool, "yt-dlp"),
    attempt: Paths.signinAttemptDir(paths, 1)
  }
  b.profile = b.attempt + "/profile"
  return b
}

function run(script, zero, args, input) {
  var options = { encoding: "utf8", cwd: top, env: { PATH: "/usr/bin", LANG: "C.UTF-8" } }
  if (typeof input === "string") options.input = input
  var result = childProcess.spawnSync(SH, ["-c", script, zero].concat(args), options)
  return { status: result.status, stdout: result.stdout, stderr: result.stderr }
}

function prepareData(b) {
  var result = run(Sh.PREPARE_DATA, "omajuke-prepare-data", [b.paths.dataDir, b.paths.jarFile])
  result.tokens = result.stdout.split("\n").filter(Boolean)
  return result
}

function signinDirs(b, family, input) {
  return run(Sh.SIGNIN_DIRS, "omajuke-signin-dirs", [b.attempt, family], input)
}

// A test directory in which the browser stage is over: the data directory is
// prepared, the attempt directory exists, and the stand-in will write these
// lines as the profile's cookies.
function ready(lines, homeName) {
  var b = box(homeName)
  assert.deepStrictEqual(prepareData(b).tokens, ["ok"])
  assert.strictEqual(signinDirs(b, "chromium").status, 0)
  fs.writeFileSync(path.join(b.tool, "mode"), "write")
  fs.writeFileSync(path.join(b.tool, "rows"), exported(lines))
  return b
}

function exportArgs(b, name) {
  return [name === undefined ? "chrome" : name, b.profile, b.attempt, b.paths.jarFile, b.ytdlp]
}

function cookieExport(b, name) {
  return run(Sh.COOKIE_EXPORT, "omajuke-export", exportArgs(b, name))
}

function calls(b) {
  var file = path.join(b.tool, "log")
  if (!exists(file)) return []
  var lines = fs.readFileSync(file, "utf8").split("\n").filter(Boolean)
  return lines.map(function(line) { return JSON.parse(line) })
}

function mode(file) {
  return (fs.lstatSync(file).mode & 0o7777).toString(8)
}

function exists(file) {
  try {
    fs.lstatSync(file)
    return true
  } catch (error) {
    return false
  }
}

function names(dir) {
  return fs.readdirSync(dir).sort()
}

